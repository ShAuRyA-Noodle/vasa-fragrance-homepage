// Builds "The Exhibition" story into each product page from products/exhibition/catalog.js.
// Keeps the site shell (header, panels, details, reviews, footer) and replaces only the
// story + purchase area and the related-fragrances row. Safe to re-run.
// Usage: node scripts/build-exhibition.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { exhibitions } from '../products/exhibition/catalog.js';

const bottles = JSON.parse(readFileSync('public/bottles/manifest.json', 'utf8'));
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const ROMAN = ['I', 'II', 'III'];
const SLOT = ['opening', 'heart', 'base'];
const lum = (hex) => { const n = parseInt(hex.slice(1), 16); return (0.299 * (n >> 16) + 0.587 * ((n >> 8) & 255) + 0.114 * (n & 255)) / 255; };

function geometry(id) {
  const b = bottles[id];
  const foot = b.baseY, top = b.topY ?? (2 * b.baseY - 1);
  return { aspect: +(b.width / b.height).toFixed(4), foot: +foot.toFixed(4), top: +top.toFixed(4) };
}

function rootStyle(p, g) {
  const c = p.palette;
  return [
    `--damask:${c.damask}`, `--damask-2:${c.damask2}`, `--damask-deep:${c.deep}`,
    `--salon-bg:${c.salon}`, `--adm-bg:${c.admission}`, `--exc-bg:${c.excursion}`,
    `--shade:${c.shade}`, `--btn:${c.button}`, `--btn-hover:${c.buttonHover}`,
    `--tint-1:${c.tints[0]}`, `--tint-2:${c.tints[1]}`, `--tint-3:${c.tints[2]}`,
    `--b-aspect:${g.aspect}`, `--b-foot:${(g.foot * 100).toFixed(2)}%`,
  ].join(';');
}

